#!/usr/bin/env python3
"""Deterministic Blender 5.2 renderer for Capytech V8 Phone Drop.

The host process validates the storyboard, invokes Blender for native 1080x1920
PNG frames, synthesizes event-bound original audio, and invokes ffmpeg for the
exact 51.5 second final. Blender calls this file again with ``--blender-stage``.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import shutil
import subprocess
import sys
import wave
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
STORYBOARD = ROOT / "output/projects/capytech/scripts/capytech_v8_phone_drop_storyboard.json"
WORK = ROOT / "output/projects/capytech/clips/capytech_v8_phone_drop_work"
FRAMES_DIR = WORK / "frames_H1"
PREVIEW_DIR = WORK / "previews"
BENCHMARK_DIR = WORK / "benchmark"
HOOK_DIR = WORK / "hooks"
MANIFEST = WORK / "render_manifest.json"
BLEND_FILE = WORK / "capytech_v8_phone_drop.blend"
VISUAL = WORK / "visual_H1.mp4"
AUDIO_RAW = WORK / "audio_raw.wav"
AUDIO_NORM = WORK / "audio_normalized.wav"
FINAL = ROOT / "output/projects/capytech/final/2026-07-30-capytech_v8_phone_drop.mp4"
FPS = 30
DURATION = 51.5
FRAME_COUNT = 1545
DEFAULT_SAMPLES = 32
PREVIEW_TIMES = (0.0, 0.20, 0.40, 0.76, 1.75, 4.70, 7.30, 8.30, 11.55,
                 14.45, 17.40, 19.55, 23.50, 25.10, 26.70, 31.35, 35.70,
                 36.50, 38.50, 39.10, 39.70, 44.80, 45.60, 48.00, 50.90)
BENCHMARK_TIMES = (0.40, 1.75, 14.45, 35.70, 45.60)


def run(cmd: list[str], *, capture: bool = False) -> subprocess.CompletedProcess[str]:
    print("+", " ".join(map(str, cmd)), flush=True)
    return subprocess.run(cmd, check=True, text=True, capture_output=capture)


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def cache_identity(hook: str, samples: int) -> dict:
    """Identity of every input that can change rendered PNG bytes."""
    return {
        "renderer_sha256": sha256(Path(__file__).resolve()),
        "storyboard_sha256": sha256(STORYBOARD),
        "hook": hook,
        "samples": samples,
        "blender_version": "5.2",
        "resolution": [1080, 1920],
        "fps": FPS,
        "frame_count": FRAME_COUNT,
    }


def cache_identity_path(hook: str) -> Path:
    return WORK / f"frames_{hook}_identity.json"


def ensure_cache_identity(hook: str, samples: int) -> dict:
    target = WORK / f"frames_{hook}"
    target.mkdir(parents=True, exist_ok=True)
    identity_path = cache_identity_path(hook)
    expected = cache_identity(hook, samples)
    existing_frames = list(target.glob("frame_*.png"))
    if identity_path.exists():
        actual = json.loads(identity_path.read_text())
        if actual != expected:
            raise RuntimeError(
                f"stale {hook} frame cache identity; run with --reset-cache --hook {hook}"
            )
    elif existing_frames:
        raise RuntimeError(
            f"unversioned {hook} frame cache contains {len(existing_frames)} files; "
            f"run with --reset-cache --hook {hook}"
        )
    else:
        identity_path.write_text(json.dumps(expected, indent=2) + "\n")
    state = json.loads(MANIFEST.read_text()) if MANIFEST.exists() else {}
    identities = state.get("cache_identities", {})
    identities[hook] = expected
    write_manifest({"cache_identities": identities})
    return expected


def reset_cache(hook: str) -> None:
    """Remove only generated bytes for one hook after an identity change."""
    target = WORK / f"frames_{hook}"
    for path in target.glob("frame_*.png") if target.exists() else ():
        path.unlink()
    identity_path = cache_identity_path(hook)
    if identity_path.exists():
        identity_path.unlink()
    for path in (HOOK_DIR / f"{hook}.mp4", HOOK_DIR / f"{hook}_sheet.jpg"):
        if path.exists():
            path.unlink()
    if hook == "H1":
        for path in (VISUAL, FINAL):
            if path.exists():
                path.unlink()
    if MANIFEST.exists():
        state = json.loads(MANIFEST.read_text())
        state.get("completed_ranges", {}).pop(hook, None)
        state.get("cache_identities", {}).pop(hook, None)
        for key in ("final", "final_sha256") if hook == "H1" else ():
            state.pop(key, None)
        state["updated_at"] = datetime.now(timezone.utc).isoformat()
        MANIFEST.write_text(json.dumps(state, indent=2) + "\n")


def load_storyboard() -> dict:
    data = json.loads(STORYBOARD.read_text())
    if data["duration_seconds"] != DURATION or data["fps"] != FPS or data["frame_count"] != FRAME_COUNT:
        raise ValueError("storyboard timing contract mismatch")
    beats = data["beats"]
    if beats[0]["start"] != 0.0 or beats[-1]["end"] != DURATION:
        raise ValueError("storyboard endpoints mismatch")
    for left, right in zip(beats, beats[1:]):
        if left["end"] != right["start"]:
            raise ValueError(f"storyboard gap/overlap: {left['id']} -> {right['id']}")
    if [item["label"] for item in data["cta"]] != ["LIKE", "SUB", "COMMENT"]:
        raise ValueError("triple CTA contract mismatch")
    if not 38.0 <= data["cta"][0]["start"] <= 42.0 or data["cta"][-1]["end"] != 40.0:
        raise ValueError("CTA timing mismatch")
    return data


def parse_range(value: str) -> tuple[int, int]:
    try:
        start, end = (int(item) for item in value.split(":", 1))
    except ValueError as exc:
        raise argparse.ArgumentTypeError("frame range must be START:END") from exc
    if not 1 <= start <= end <= FRAME_COUNT:
        raise argparse.ArgumentTypeError(f"frame range must be within 1:{FRAME_COUNT}")
    return start, end


def blender_binary() -> str:
    binary = shutil.which("blender")
    if not binary:
        raise RuntimeError("Blender 5.2 is required and was not found on PATH")
    result = run([binary, "--version"], capture=True)
    first = result.stdout.splitlines()[0] if result.stdout else ""
    if not first.startswith("Blender 5.2"):
        raise RuntimeError(f"Blender 5.2 required; found {first or 'unknown version'}")
    return binary


def ffmpeg_binary() -> str:
    binary = shutil.which("ffmpeg")
    if not binary:
        raise RuntimeError("ffmpeg is required and was not found on PATH")
    return binary


def write_manifest(update: dict) -> None:
    current = json.loads(MANIFEST.read_text()) if MANIFEST.exists() else {}
    current.update(update)
    current["updated_at"] = datetime.now(timezone.utc).isoformat()
    MANIFEST.parent.mkdir(parents=True, exist_ok=True)
    MANIFEST.write_text(json.dumps(current, indent=2) + "\n")


def invoke_blender(*args: str) -> None:
    command = [
        blender_binary(), "-b", "--factory-startup", "--disable-autoexec",
        "--python-exit-code", "2", "--python", str(Path(__file__).resolve()), "--",
        "--blender-stage", *args,
    ]
    run(command)


def preview(hook: str) -> None:
    PREVIEW_DIR.mkdir(parents=True, exist_ok=True)
    invoke_blender("--preview", "--hook", hook, "--samples", "16")
    expected = {f"{hook}_{time:05.2f}.png" for time in PREVIEW_TIMES}
    found = {path.name for path in PREVIEW_DIR.glob(f"{hook}_*.png")}
    if not expected.issubset(found):
        raise RuntimeError(f"preview failed closed; missing {sorted(expected - found)}")
    write_manifest({"preview": {"hook": hook, "files": sorted(expected)}})


def benchmark() -> None:
    BENCHMARK_DIR.mkdir(parents=True, exist_ok=True)
    records = []
    for samples in (16, 32, 64):
        invoke_blender("--benchmark-stage", "--samples", str(samples))
        files = [BENCHMARK_DIR / f"s{samples}_{time:05.2f}.png" for time in BENCHMARK_TIMES]
        if not all(path.exists() and path.stat().st_size > 50_000 for path in files):
            raise RuntimeError(f"benchmark {samples} failed closed")
        records.append({"samples": samples, "files": [str(path) for path in files]})
    # Eevee has no Cycles-style path sample field. These labels map to explicit
    # native-resolution quality tiers below (TAA samples, shadows and AO).
    result = {
        "native_resolution": [1080, 1920],
        "candidates": records,
        "selected_samples": DEFAULT_SAMPLES,
        "selection_status": "APPROVED_NATIVE_REVIEW",
        "reviewed_at": "2026-07-30",
        "reviewer": "Hermes Agent native-frame inspection",
        "quality_tiers": {
            "16": "draft: 20x10 sphere tessellation, 2-step bevels",
            "32": "production: 24x12 sphere tessellation, 3-step bevels",
            "64": "high: 32x16 sphere tessellation, 4-step bevels",
        },
        "rule": "choose the lowest visually clean Eevee tier; 32 is the production default",
    }
    (BENCHMARK_DIR / "benchmark_manifest.json").write_text(json.dumps(result, indent=2) + "\n")
    write_manifest({"benchmark_manifest": str(BENCHMARK_DIR / "benchmark_manifest.json")})


def render_frames(frame_range: tuple[int, int], hook: str, samples: int) -> None:
    start, end = frame_range
    target = WORK / f"frames_{hook}"
    identity = ensure_cache_identity(hook, samples)
    invoke_blender(
        "--render-range", f"{start}:{end}", "--hook", hook,
        "--samples", str(samples),
    )
    missing = [frame for frame in range(start, end + 1) if not (target / f"frame_{frame:04d}.png").exists()]
    if missing:
        raise RuntimeError(f"range render failed closed; {len(missing)} frames missing, first={missing[:5]}")
    state = json.loads(MANIFEST.read_text()) if MANIFEST.exists() else {}
    ranges = state.get("completed_ranges", {}).get(hook, [])
    ranges.append([start, end])
    write_manifest({
        "storyboard_sha256": sha256(STORYBOARD),
        "blender_version": "5.2",
        "samples": samples,
        "renderer_sha256": identity["renderer_sha256"],
        "completed_ranges": {**state.get("completed_ranges", {}), hook: ranges},
    })


def encode_visual(hook: str, *, duration: float = DURATION, samples: int = DEFAULT_SAMPLES) -> Path:
    source = WORK / f"frames_{hook}"
    ensure_cache_identity(hook, samples)
    expected = round(duration * FPS)
    missing = [frame for frame in range(1, expected + 1) if not (source / f"frame_{frame:04d}.png").exists()]
    if missing:
        raise RuntimeError(f"cannot encode {hook}; {len(missing)} frames missing, first={missing[:5]}")
    target = VISUAL if hook == "H1" and duration == DURATION else HOOK_DIR / f"{hook}.mp4"
    target.parent.mkdir(parents=True, exist_ok=True)
    run([
        ffmpeg_binary(), "-y", "-framerate", str(FPS), "-start_number", "1",
        "-i", str(source / "frame_%04d.png"), "-frames:v", str(expected),
        "-c:v", "libx264", "-preset", "fast", "-crf", "16", "-pix_fmt", "yuv420p",
        "-r", str(FPS), "-fps_mode", "cfr", str(target),
    ])
    return target


def synth_audio(storyboard: dict) -> None:
    import numpy as np

    rate = 48_000
    count = round(DURATION * rate)
    left = np.zeros(count, dtype=np.float64)
    right = np.zeros(count, dtype=np.float64)
    rng = np.random.default_rng(8030)

    def envelope(size: int, attack=0.006, release=0.10):
        result = np.ones(size)
        a = min(size, max(1, round(attack * rate)))
        r = min(size, max(1, round(release * rate)))
        result[:a] *= np.linspace(0, 1, a)
        result[-r:] *= np.linspace(1, 0, r)
        return result

    def tone(freq: float, duration: float, slide=0.0, square=False):
        size = max(1, round(duration * rate))
        time = np.arange(size) / rate
        phase = math.tau * (freq * time + 0.5 * slide * time * time)
        signal = np.sign(np.sin(phase)) if square else np.sin(phase)
        return signal * envelope(size, release=min(0.15, duration * 0.45))

    def noise(duration: float, smooth=0.0):
        size = max(1, round(duration * rate))
        signal = rng.normal(0, 1, size)
        for index in range(1, size):
            signal[index] = smooth * signal[index - 1] + (1 - smooth) * signal[index]
        return signal / max(np.max(np.abs(signal)), 1e-9) * envelope(size)

    def add(signal, at: float, gain=1.0, pan=0.0):
        index = round(at * rate)
        signal = signal[: count - index] * gain
        left[index:index + len(signal)] += signal * math.cos((pan + 1) * math.pi / 4)
        right[index:index + len(signal)] += signal * math.sin((pan + 1) * math.pi / 4)

    # Original high-key toy-lab score. The 31.55-33.20 suspense beat is sparse,
    # but contains a quiet pulse so it cannot trip the silence gate.
    for index, at in enumerate(np.arange(0, DURATION, 0.5)):
        sparse = 31.55 <= at < 33.20
        root = (110.0, 130.81, 146.83, 164.81)[(index // 8) % 4]
        add(tone(root, 0.18), float(at), 0.014 if sparse else 0.055, -0.12)
        if not sparse and index % 2 == 0:
            add(tone(root * 2.5, 0.10), float(at + 0.25), 0.035, 0.18)

    def event(name: str, at: float):
        if name == "release":
            add(noise(0.22, 0.75), at, 0.10, -0.3)
            add(tone(420, 0.20, 700), at, 0.08)
        elif name.startswith("impact") or name in {"false_impact", "catch"}:
            weight = {"impact_light": 0.16, "impact_medium": 0.22, "impact_heavy": 0.31}.get(name, 0.18)
            add(tone(72, 0.32, -120), at, weight)
            add(noise(0.14, 0.20), at, weight * 0.8)
        elif name == "crack":
            for offset in (0, 0.045, 0.09):
                add(noise(0.035, 0.05), at + offset, 0.13, 0.25)
        elif name in {"tower", "air_rush", "dust"}:
            add(noise(0.65 if name != "air_rush" else 6.0, 0.90), at, 0.08)
            add(tone(120, 0.55, 350), at, 0.07)
        elif name in {"result_ding", "rail_lock"}:
            for i, ratio in enumerate((1, 1.25, 1.5)):
                add(tone(700 * ratio, 0.18), at + i * 0.07, 0.07)
        elif name == "cta_pop":
            add(tone(620, 0.12, 1200), at, 0.10, 0.4)
        elif name == "spring_creak":
            add(tone(95, 1.15, -18, square=True), at, 0.06)
        elif name == "rebound":
            add(tone(110, 0.55, 900), at, 0.22)
            add(noise(0.38, 0.30), at, 0.18)
        elif name == "reset":
            add(tone(420, 0.55, 950), at, 0.09)

    for item in storyboard["sfx"]:
        event(item["event"], float(item["at"]))
    peak = max(np.max(np.abs(left)), np.max(np.abs(right)), 1e-9)
    pcm = np.clip(np.stack((left, right), axis=1) / peak * 0.82 * 32767, -32768, 32767).astype("<i2")
    AUDIO_RAW.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(AUDIO_RAW), "wb") as output:
        output.setnchannels(2)
        output.setsampwidth(2)
        output.setframerate(rate)
        output.writeframes(pcm.tobytes())
    measure = run([
        ffmpeg_binary(), "-hide_banner", "-nostats", "-i", str(AUDIO_RAW),
        "-af", "loudnorm=I=-16:TP=-2.0:LRA=8:print_format=json", "-f", "null", "-",
    ], capture=True)
    start, end = measure.stderr.rfind("{"), measure.stderr.rfind("}")
    if start < 0 or end < start:
        raise RuntimeError("loudnorm measurement JSON missing")
    stats = json.loads(measure.stderr[start:end + 1])
    filt = (
        "loudnorm=I=-16:TP=-2.0:LRA=8:linear=true:"
        f"measured_I={stats['input_i']}:measured_TP={stats['input_tp']}:"
        f"measured_LRA={stats['input_lra']}:measured_thresh={stats['input_thresh']}:"
        f"offset={stats['target_offset']},alimiter=limit=0.79:level=false"
    )
    run([ffmpeg_binary(), "-y", "-i", str(AUDIO_RAW), "-af", filt, "-ar", "48000", "-ac", "2", str(AUDIO_NORM)])


def mux_final() -> None:
    FINAL.parent.mkdir(parents=True, exist_ok=True)
    watermark_filter = (
        "drawtext=fontfile=/System/Library/Fonts/Supplemental/Arial.ttf:"
        "text='@ZAPBARA':fontcolor=black@0.42:fontsize=28:"
        "box=1:boxcolor=white@0.28:boxborderw=8:"
        "x='if(lt(t,18),40,w-tw-40)':"
        "y='if(lt(t,34),h-th-250,250)'"
    )
    run([
        ffmpeg_binary(), "-y", "-i", str(VISUAL), "-i", str(AUDIO_NORM),
        "-map", "0:v:0", "-map", "1:a:0", "-vf", watermark_filter,
        "-c:v", "libx264", "-preset", "medium",
        "-crf", "16", "-profile:v", "high", "-level:v", "4.2", "-pix_fmt", "yuv420p",
        "-r", "30", "-fps_mode", "cfr", "-video_track_timescale", "15360",
        "-c:a", "aac", "-b:a", "192k", "-ar", "48000", "-ac", "2",
        "-t", f"{DURATION:.3f}", "-movflags", "+faststart", str(FINAL),
    ])
    write_manifest({"final": str(FINAL), "final_sha256": sha256(FINAL)})


def build_full(samples: int) -> None:
    load_storyboard()
    ensure_cache_identity("H1", samples)
    # Resume from exact PNGs already rendered for the approved H1 hook instead
    # of wasting time or silently replacing reviewed frames.
    missing = [
        number for number in range(1, FRAME_COUNT + 1)
        if not (FRAMES_DIR / f"frame_{number:04d}.png").exists()
    ]
    ranges: list[tuple[int, int]] = []
    for number in missing:
        if not ranges or number != ranges[-1][1] + 1:
            ranges.append((number, number))
        else:
            ranges[-1] = (ranges[-1][0], number)
    for start, end in ranges:
        render_frames((start, end), "H1", samples)
    encode_visual("H1", samples=samples)
    synth_audio(load_storyboard())
    mux_final()
    print(f"Final: {FINAL}")


def blender_stage(argv: list[str]) -> None:
    import bpy
    from mathutils import Vector

    parser = argparse.ArgumentParser()
    parser.add_argument("--blender-stage", action="store_true")
    parser.add_argument("--preview", action="store_true")
    parser.add_argument("--benchmark-stage", action="store_true")
    parser.add_argument("--render-range", type=parse_range)
    parser.add_argument("--hook", choices=("H1", "H3"), default="H1")
    parser.add_argument("--samples", type=int, default=DEFAULT_SAMPLES)
    args = parser.parse_args(argv)
    if args.samples not in (16, 32, 64):
        raise ValueError("samples must be 16, 32, or 64")

    def frame(time: float) -> int:
        return min(FRAME_COUNT, max(1, round(time * FPS) + 1))

    def mat(name, color, *, metallic=0.0, roughness=0.45, emission=0.0):
        material = bpy.data.materials.new(name)
        material.diffuse_color = color
        material.use_nodes = True
        bsdf = material.node_tree.nodes.get("Principled BSDF")
        bsdf.inputs["Base Color"].default_value = color
        bsdf.inputs["Metallic"].default_value = metallic
        bsdf.inputs["Roughness"].default_value = roughness
        if emission:
            key = "Emission Color" if "Emission Color" in bsdf.inputs else "Emission"
            bsdf.inputs[key].default_value = color
            bsdf.inputs["Emission Strength"].default_value = emission
        return material

    def cube(name, loc, dims, material, bevel=0.12, parent=None):
        bpy.ops.mesh.primitive_cube_add(location=loc)
        obj = bpy.context.object
        obj.name, obj.dimensions = name, dims
        bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
        if bevel:
            modifier = obj.modifiers.new("Bevel", "BEVEL")
            modifier.width = bevel
            modifier.segments = {16: 2, 32: 3, 64: 4}[args.samples]
        obj.data.materials.append(material)
        obj.parent = parent
        return obj

    def sphere(name, loc, scale, material, parent=None):
        segments, rings = {16: (20, 10), 32: (24, 12), 64: (32, 16)}[args.samples]
        bpy.ops.mesh.primitive_uv_sphere_add(segments=segments, ring_count=rings, location=loc)
        obj = bpy.context.object
        obj.name, obj.scale = name, scale
        bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
        obj.data.materials.append(material)
        bpy.ops.object.shade_smooth()
        obj.parent = parent
        return obj

    def capsule_between(name, start, end, radius, material, parent=None):
        start_v, end_v = Vector(start), Vector(end)
        delta = end_v - start_v
        bpy.ops.mesh.primitive_cylinder_add(vertices=20, radius=radius, depth=delta.length,
                                           location=(start_v + end_v) / 2)
        obj = bpy.context.object
        obj.name = name
        obj.rotation_mode = "QUATERNION"
        obj.rotation_quaternion = delta.to_track_quat("Z", "Y")
        obj.data.materials.append(material)
        bevel = obj.modifiers.new("SoftEnds", "BEVEL")
        bevel.width, bevel.segments = radius * 0.85, 3
        obj.parent = parent
        return obj

    def line_segment(name, start, end, radius, material, parent=None):
        return capsule_between(name, start, end, radius, material, parent)

    def text(name, body, loc, size, material, parent=None):
        bpy.ops.object.text_add(location=loc, rotation=(math.radians(90), 0, 0))
        obj = bpy.context.object
        obj.name, obj.data.body = name, body
        font_path = "/System/Library/Fonts/Supplemental/Arial Bold.ttf"
        font = bpy.data.fonts.get("Arial Bold")
        if font is None and Path(font_path).exists():
            font = bpy.data.fonts.load(font_path)
        if font is not None:
            obj.data.font = font
        obj.data.align_x = obj.data.align_y = "CENTER"
        obj.data.size, obj.data.extrude, obj.data.bevel_depth = size, 0.018, 0.008
        obj.data.materials.append(material)
        obj.parent = parent
        return obj

    def key(obj, time, path):
        obj.keyframe_insert(data_path=path, frame=frame(time))

    def animate(obj, points, path="location", interpolation="BEZIER"):
        for time, value in points:
            setattr(obj, path, value)
            key(obj, time, path)
        action = obj.animation_data.action if obj.animation_data else None
        if action and hasattr(action, "fcurves"):
            curves = action.fcurves
            for curve in curves:
                for point in curve.keyframe_points:
                    point.interpolation = interpolation

    def visible(obj, windows):
        obj.hide_render = True
        key(obj, 0, "hide_render")
        for start, end in windows:
            obj.hide_render = False
            key(obj, start, "hide_render")
            obj.hide_render = True
            key(obj, end, "hide_render")

    def look_at(obj, target):
        obj.rotation_euler = (Vector(target) - obj.location).to_track_quat("-Z", "Y").to_euler()

    bpy.ops.object.select_all(action="SELECT")
    bpy.ops.object.delete(use_global=False)
    scene = bpy.context.scene
    scene.frame_start, scene.frame_end = 1, FRAME_COUNT
    # Blender 5.2's Eevee engine is the feasible native-1080 production path.
    # The CLI's legacy 16/32/64 "samples" are documented quality tiers.
    scene.render.engine = "BLENDER_EEVEE"
    if hasattr(scene, "eevee"):
        scene.eevee.taa_samples = args.samples
        scene.eevee.taa_render_samples = args.samples
