def main() -> None:
    if "--blender-stage" in sys.argv:
        blender_stage(sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else [])
        return
    parser = argparse.ArgumentParser()
    parser.add_argument("--preview", action="store_true")
    parser.add_argument("--hook", choices=("H1", "H3"), default="H1")
    parser.add_argument("--benchmark", action="store_true")
    parser.add_argument("--frames", type=parse_range)
    parser.add_argument("--samples", type=int, choices=(16, 32, 64), default=DEFAULT_SAMPLES)
    parser.add_argument("--reset-cache", action="store_true", help="Delete generated frames for the selected hook before rendering")
    parser.add_argument("--encode-hook", action="store_true", help="Encode already rendered 0-3s hook frames")
    args = parser.parse_args()
    load_storyboard()
    if args.reset_cache:
        reset_cache(args.hook)
    if args.preview:
        preview(args.hook)
    elif args.benchmark:
        benchmark()
    elif args.frames:
        render_frames(args.frames, args.hook, args.samples)
    elif args.encode_hook:
        encode_visual(args.hook, duration=3.0, samples=args.samples)
    else:
        build_full(args.samples)


if __name__ == "__main__":
    main()
